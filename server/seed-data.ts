export function bootstrapDatabaseIfEmpty(upsertFn: (repo: RawRepoInput) => any, db: any) {
  const count = (db.prepare('SELECT COUNT(*) as c FROM repositories').get() as any)?.c || 0;
  if (count === 0) {
    console.log('[Bootstrap] Seeding verified authentic repositories with 1000+ stars...');
    for (const repo of VERIFIED_BOOTSTRAP_REPOS) {
      const categories = classifyRepository({
        topics: repo.topics,
        language: repo.language,
        name: repo.name,
        description: repo.description
      });
      upsertFn({
        ...repo,
        categories
      });
    }
    console.log(`[Bootstrap] Successfully seeded ${VERIFIED_BOOTSTRAP_REPOS.length} verified repositories.`);
  }
}
